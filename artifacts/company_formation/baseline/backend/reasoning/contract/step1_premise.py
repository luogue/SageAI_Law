def parse_step1_output(output: str) -> Dict:
    """解析Step1的输出"""
    try:
        data = json.loads(output)
        
        # 验证必需字段
        required_fields = ["fact_time", "applicable_law_version", "core_rule", 
                          "contract_type", "premises", "principles", "structure_explanation", 
                          "is_chaotic", "structure_type", "upper_essence", "lower_essence", 
                          "layer_relation", "key_time_point", "direct_basis", "required_rule_types"]
        for field in required_fields:
            if field not in data:
                raise ValueError(f"缺少必需字段: {field}")
        
        # 验证principles格式
        if not isinstance(data["principles"], list) or len(data["principles"]) < 5:
            raise ValueError("principles必须是至少包含5个元素的列表")
        
        for principle in data["principles"]:
            if not all(k in principle for k in ["name", "score", "description"]):
                raise ValueError("principles元素格式不正确")
        
        return data
        
    except json.JSONDecodeError as e:
        logger.error(f"Step1 JSON解析失败: {e}")
        raise
    except ValueError as e:
        logger.error(f"Step1 数据格式验证失败: {e}")
        raise