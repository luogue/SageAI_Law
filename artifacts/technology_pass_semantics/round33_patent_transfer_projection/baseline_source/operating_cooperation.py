def structure(text):
    patterns = {
        'operation': r'(?:分理处|分支机构|营业部|网点|门店)[^。\n]{0,65}(?:承包经营|交由[^。\n]{0,12}经营)|承包经营[^。\n]{0,30}(?:分理处|网点|门店)',
        'authority': r'(?:授权|以甲方[^。\n]{0,15}名义|甲方合同章)',
        'return': r'(?:上交|缴纳)[^。\n]{0,25}(?:利润|管理费)|利润分配|欠收自补',
        'cost': r'(?:费用|支出)[^。\n]{0,20}(?:乙方|承包方)承担',
    }
    facts={k:m.group() for k,p in patterns.items() if (m:=re.search(p,text))}
    return {'established':len(facts)==4, 'facts':facts,
        'downstream_contracts':bool(re.search(r'(?:另行|起草)[^。\n]{0,30}合同|合同[^。\n]{0,20}另行签',text))}

